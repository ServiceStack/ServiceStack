using System;
using System.IO;
using System.Linq;
using NUnit.Framework;
using ServiceStack.AI;

namespace ServiceStack.Extensions.Tests;

[TestFixture]
public class PdfCodeGenTests
{
    string root = null!;
    string output = null!;

    [SetUp]
    public void SetUp()
    {
        root = Path.Combine(Path.GetTempPath(), "pdf-codegen-" + Guid.NewGuid().ToString("N"));
        output = Path.Combine(root, "models");
        Directory.CreateDirectory(root);
        File.WriteAllText(Path.Combine(root, "namespaced-test.typ"), "#let value = data.name");
        File.WriteAllText(Path.Combine(root, "namespaced-test.ui.json"), Schema);
    }

    [TearDown]
    public void TearDown()
    {
        if (Directory.Exists(root))
            Directory.Delete(root, recursive: true);
    }

    [Test]
    public void PdfAttribute_namespace_overrides_generated_namespace_without_changing_output_path()
    {
        var feature = new PdfFeature {
            PdfPath = root,
            ModelsPath = output,
            ModelsNamespace = "Default.Pdf.Models",
        };
        var config = new PdfCodeGenConfig();

        var result = new PdfCodeGen(feature).Generate(config);

        Assert.That(result.Errors, Is.Empty);
        Assert.That(result.Generated, Is.EqualTo(new[] { "NamespacedDocument.cs" }));
        var path = Path.Combine(output, "NamespacedDocument.cs");
        Assert.That(File.Exists(path), Is.True);

        var source = File.ReadAllText(path);
        Assert.That(new PdfCodeGen(feature).CreateFile("namespaced-test", config).Namespace,
            Is.EqualTo("Custom.Pdf.Models"));
        Assert.That(source, Does.Contain("namespace Custom.Pdf.Models;"));
        Assert.That(source, Does.Contain(
            "[Pdf(\"namespaced-test\", Namespace = \"Custom.Pdf.Models\")]"));

        Assert.That(source, Does.StartWith(PdfCodeGen.HeaderPrefix));

        var secondRun = new PdfCodeGen(feature).Generate(config);
        Assert.That(secondRun.Generated, Is.Empty);
        Assert.That(secondRun.Unchanged, Is.EqualTo(new[] { "NamespacedDocument.cs" }));
    }

    [Test]
    public void Auto_generated_marker_controls_file_ownership()
    {
        var feature = new PdfFeature {
            PdfPath = root,
            ModelsPath = output,
            ModelsNamespace = "Default.Pdf.Models",
        };
        var config = new PdfCodeGenConfig();
        var path = Path.Combine(output, "NamespacedDocument.cs");

        new PdfCodeGen(feature).Generate(config);

        File.WriteAllText(Path.Combine(root, "namespaced-test.ui.json"), SchemaWithAge);
        var regenerateMarked = new PdfCodeGen(feature).Generate(config);
        Assert.That(regenerateMarked.Generated, Is.EqualTo(new[] { "NamespacedDocument.cs" }));
        Assert.That(File.ReadAllText(path), Does.Contain("public int Age"));

        var unmarked = File.ReadAllText(path).Replace(PdfCodeGen.HeaderPrefix + "\n", "");
        File.WriteAllText(path, unmarked + "\n// developer-owned");
        File.WriteAllText(Path.Combine(root, "namespaced-test.ui.json"), SchemaWithAgeAndActive);

        var preserveUnmarked = new PdfCodeGen(feature).Generate(config);
        Assert.That(preserveUnmarked.Generated, Is.Empty);
        Assert.That(preserveUnmarked.Skipped.Single(), Does.Contain("has no <auto-generated> marker"));
        Assert.That(File.ReadAllText(path), Does.Contain("developer-owned"));
        Assert.That(File.ReadAllText(path), Does.Not.Contain("public bool Active"));
    }

    const string Schema = """
    {
      "title":"NamespacedDocument",
      "type":"object",
      "required":["name"],
      "properties":{"name":{"type":"string"}}
    }
    """;

    const string SchemaWithAge = """
    {
      "title":"NamespacedDocument",
      "type":"object",
      "required":["name","age"],
      "properties":{"name":{"type":"string"},"age":{"type":"integer"}}
    }
    """;

    const string SchemaWithAgeAndActive = """
    {
      "title":"NamespacedDocument",
      "type":"object",
      "required":["name","age","active"],
      "properties":{"name":{"type":"string"},"age":{"type":"integer"},"active":{"type":"boolean"}}
    }
    """;
}

[Pdf("namespaced-test", Namespace = "Custom.Pdf.Models")]
public class NamespacedPdfModel { }
